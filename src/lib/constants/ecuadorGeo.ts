export const LISTA_PROVINCIAS_ECUADOR = Object.keys(PROVINCIAS_CANTONES_ECUADOR);

/**
 * Obtiene los cantones o sectores de una provincia dada.
 * Si no existe, retorna una lista con la capital o cabecera cantonal.
 */
export function getCantonesPorProvincia(provincia: string): string[] {
  if (!provincia) return PROVINCIAS_CANTONES_ECUADOR['Pichincha'];
  
  // Búsqueda insensible a mayúsculas y acentos
  const normalizada = provincia.trim().toLowerCase();
  for (const [key, cantones] of Object.entries(PROVINCIAS_CANTONES_ECUADOR)) {
    if (key.toLowerCase() === normalizada) {
      return cantones;
    }
  }

  // Fallback si contiene coincidencia parcial
  for (const [key, cantones] of Object.entries(PROVINCIAS_CANTONES_ECUADOR)) {
    if (key.toLowerCase().includes(normalizada) || normalizada.includes(key.toLowerCase())) {
      return cantones;
    }
  }

  return ['Centro Cantonal', 'Cabecera Parroquial'];
}
